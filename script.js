function resolveProjectKey(cardEl) {
  if (!cardEl) return null;
  const rawAttr = (
    cardEl.getAttribute("data-project") ||
    cardEl.getAttribute("data-project-id") ||
    cardEl.getAttribute("data-slug") ||
    cardEl.getAttribute("data-id") ||
    ""
  ).toLowerCase().trim();
  if (rawAttr && CASPER_PROJECTS[rawAttr]) return rawAttr;
  if (rawAttr && PROJECT_ALIASES[rawAttr]) return PROJECT_ALIASES[rawAttr];

  // Zoek op basis van h3/h2 titel in de kaart
  const heading = cardEl.querySelector("h2, h3, h4, .project-title, .card-title");
  if (heading) {
    const t = heading.textContent.toLowerCase().trim();
    if (PROJECT_ALIASES[t]) return PROJECT_ALIASES[t];
    for (const [k, v] of Object.entries(CASPER_PROJECTS)) {
      if (t.includes(k.replace(/-/g, " ")) || v.title.toLowerCase().includes(t)) return k;
    }
  }

  // Zoek op basis van de <img src="..."> in de kaart
  const img = cardEl.querySelector("img");
  if (img && img.getAttribute("src")) {
    const src = img.getAttribute("src").toLowerCase();
    for (const k of Object.keys(CASPER_PROJECTS)) {
      if (src.includes(k)) return k;
    }
  }
  return null;
}

function ensureUniversalModal() {
  let modal = document.getElementById("casper-universal-modal");
  if (!modal) {
    modal = document.createElement("div");
    modal.id = "casper-universal-modal";
    modal.setAttribute("role", "dialog");
    modal.setAttribute("aria-modal", "true");
    modal.innerHTML = `
      <div class="cum-dialog">
        <button class="cum-close" id="cum-close-btn" aria-label="Sluiten">×</button>
        <p id="cum-cat" style="color:#C87D4B;font-family:'JetBrains Mono',monospace;font-size:0.85rem;margin-bottom:0.4rem;"></p>
        <h2 id="cum-title" style="font-size:2rem;margin-bottom:0.8rem;color:#F4F1EA;"></h2>
        <p id="cum-desc" style="color:#A8A095;line-height:1.65;max-width:75ch;"></p>
        <div id="cum-gallery" class="cum-gallery"></div>
      </div>
    `;
    document.body.appendChild(modal);

    modal.addEventListener("click", (e) => {
      if (e.target === modal || e.target.closest("#cum-close-btn")) {
        closeUniversalModal();
      }
    });
  }
  return modal;
}

function openProjectModal(projKey) {
  const data = CASPER_PROJECTS[projKey];
  if (!data) return;
  const modal = ensureUniversalModal();
  document.getElementById("cum-cat").textContent = data.category || "Project Dossier";
  document.getElementById("cum-title").textContent = data.title;
  document.getElementById("cum-desc").textContent = data.description;

  const gal = document.getElementById("cum-gallery");
  gal.innerHTML = "";
  const imgs = (data.images && data.images.length) ? data.images : [data.cover];
  imgs.forEach((src, idx) => {
    if (!src) return;
    const imgEl = document.createElement("img");
    imgEl.src = src;
    imgEl.alt = `${data.title} - beeld ${idx + 1}`;
    imgEl.loading = "lazy";
    gal.appendChild(imgEl);
  });

  modal.classList.add("is-open");
  document.body.style.overflow = "hidden";
}

function closeUniversalModal() {
  const modal = document.getElementById("casper-universal-modal");
  if (modal) modal.classList.remove("is-open");
  // Sluit voor de zekerheid ook eventuele oudere modals in index.html
  document.querySelectorAll(".modal, .project-modal, #project-modal, #modal-overlay").forEach(el => {
    el.classList.remove("active", "open", "is-open");
    el.style.display = "none";
  });
  document.body.style.overflow = "";
}

document.addEventListener("DOMContentLoaded", () => {
  ensureUniversalModal();

  // Fix automatisch kaart-afbeeldingen en titels op de pagina volgens Caspers feedback
  document.querySelectorAll(".project-card, article, [data-project], [data-project-id]").forEach(card => {
    const key = resolveProjectKey(card);
    if (!key || !CASPER_PROJECTS[key]) return;
    card.setAttribute("data-project", key);
    const info = CASPER_PROJECTS[key];
    const h = card.querySelector("h2, h3, h4, .project-title, .card-title");
    if (h && key === "school-projecten") {
      h.textContent = "Dan maar hier!";
    }
    const img = card.querySelector("img");
    if (img && info.cover) {
      img.src = info.cover;
    }
  });

  // Event delegation op de hele pagina: klikken op een projectkaart opent ALTIJD de modal!
  document.body.addEventListener("click", (e) => {
    const card = e.target.closest(".project-card, [data-project], [data-project-id], .work-item, .portfolio-item, article");
    if (card && !e.target.closest("#casper-universal-modal")) {
      const key = resolveProjectKey(card);
      if (key) {
        e.preventDefault();
        openProjectModal(key);
      }
    }
  });

  document.addEventListener("keydown", (e) => {
    if (e.key === "Escape") closeUniversalModal();
  });
});
